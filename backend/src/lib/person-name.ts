/** สามช่องที่ประกอบเป็นชื่อ — `select` ของ Prisma ใช้ค่านี้ได้ตรง ๆ */
export const NAME_FIELDS = {
  prefixTh: true,
  firstnameTh: true,
  lastnameTh: true,
} as const;

export interface ThaiName {
  prefixTh?: string | null;
  firstnameTh?: string | null;
  lastnameTh?: string | null;
}

/**
 * `"นาย สมชาย ใจดี"` — เว้นวรรคระหว่างทั้งสามส่วน
 *
 * คืนค่าว่างเมื่อไม่มีชื่อไทยเลย ไม่ใช่ `null` เพราะปลายทางเกือบทั้งหมดต่อสตริง
 *
 * **คำนำหน้าอย่างเดียวไม่นับว่าเป็นชื่อ** — บัญชีที่มีแต่ `prefix_th` ยังถือว่าไม่มีชื่อ
 * ไม่งั้นจะได้ `display_name` เป็นคำว่า "นาย" ลอย ๆ ซึ่งแย่กว่าค่าว่าง
 */
export function fullNameTh(person: ThaiName | null | undefined): string {
  if (!person) return "";
  const first = person.firstnameTh?.trim() ?? "";
  const last = person.lastnameTh?.trim() ?? "";
  if (!first && !last) return "";
  const prefix = person.prefixTh?.trim() ?? "";
  return [prefix, first, last].filter(Boolean).join(" ");
}

/**
 * ชื่อไทยเต็มของบัญชีหนึ่ง อ่านสดจากฐานข้อมูล — ใช้ตอนต้องประทับว่า "ตอนนี้ใครเป็นคนทำ"
 *
 * session ถือแค่ id กับอีเมล (ตั้งใจให้เบา) ชื่อจึงต้องอ่านทุกครั้ง คืนสตริงว่างเมื่อบัญชี
 * ยังไม่มีชื่อไทย — **ไม่ตกไปใช้อีเมลแทน** ตามกฎของไฟล์นี้ บัญชีที่ยังไม่มีชื่อคือบัญชีที่
 * ยังเปิดใช้งานไม่เสร็จ ซึ่งเปิดอ่านเอกสารไม่ได้อยู่แล้ว
 */
export async function accountNameTh(
  db: Pick<PrismaClient, "userAccount"> | Prisma.TransactionClient,
  userId: string,
): Promise<string> {
  const account = await db.userAccount.findUnique({
    where: { id: userId },
    select: NAME_FIELDS,
  });
  return fullNameTh(account);
}
