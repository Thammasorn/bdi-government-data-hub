/** ชื่อช่องฝั่ง API — ชื่อเดียวกับที่ `tickFields()` ใน lib/document-render.ts ใช้ */
export const CHOICE_FIELD_KEYS = [
  "dataType",
  "dataTopic",
  "updateFrequencyUnit",
  "deliveryFrequency",
  "geoCoverage",
  "dataFormat",
  "dataCategory",
  "personalDataProcessingPeriod",
  "dataClassification",
  "licenseId",
] as const;

export type ChoiceFieldKey = (typeof CHOICE_FIELD_KEYS)[number];

export interface ChoiceDefault {
  fieldKey: ChoiceFieldKey;
  code: string;
  labelTh: string;
  displayOrder: number;
}

/**
 * ตัวช่วยประกาศ — ลำดับที่เขียนในอาร์เรย์คือ displayOrder (1, 2, 3, …)
 * เขียนเป็นอาร์เรย์ ไม่ใช่ออบเจ็กต์ เพราะคีย์ของออบเจ็กต์ที่เป็น "เลขจำนวนเต็มพอดี"
 * ("10" "11" "98" "99") ถูก JS ยกขึ้นก่อนคีย์ที่มีศูนย์นำเสมอ ซึ่งเป็นบั๊กเดิมของ
 * ลำดับตัวเลือกบนหน้าจอก่อน 2026-09-07
 */
const list = (fieldKey: ChoiceFieldKey, rows: Array<[string, string]>): ChoiceDefault[] =>
  rows.map(([code, labelTh], index) => ({ fieldKey, code, labelTh, displayOrder: index + 1 }));

