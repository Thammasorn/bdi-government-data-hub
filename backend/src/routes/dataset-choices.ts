/**
 * ตัวเลือกของแบบฟอร์มลงทะเบียนชุดข้อมูล สำหรับหน้าเว็บ
 *
 * เดิมหน้าเว็บถือสำเนาของรายการนี้ไว้เองใน `frontend/lib/dataset-form.ts` การเพิ่ม
 * ตัวเลือกหรือแก้ป้ายสักตัวจึงต้อง build frontend ใหม่ ตอนนี้แถวอยู่ในฐานข้อมูลและ
 * แอดมินแก้ได้ผ่าน `/api/admin/dataset-choices` หน้าเว็บจึงต้องมาถาม
 *
 * ไม่ต้องล็อกอิน แบบเดียวกับ `/api/address` — เป็นรายการรหัสของมาตรฐานบัญชีข้อมูลเปิด
 * ภาครัฐ ไม่ใช่ข้อมูลของหน่วยงานใด
 *
 * คืนเฉพาะตัวเลือกที่ยังเปิดอยู่ เรียงตาม display_order มาแล้ว — ลำดับบนหน้าจอเป็นของ
 * ฐานข้อมูล หน้าเว็บไม่ต้องรู้ว่า "ไม่มี / ไม่ทราบ / อื่น ๆ" ควรอยู่ท้ายรายการ
 */
import { Router } from "../lib/async-route.js";

import { activeChoiceMap } from "../lib/dataset-choices.js";

export const datasetChoiceRouter = Router();

/**
 * `no-cache` = ถามทุกครั้ง แต่ยอมให้ตอบ 304 ได้ — **ไม่ใช่** "ห้าม cache"
 *
 * `/api/address` ใช้ `max-age=86400` ได้เพราะรายชื่อจังหวัดไม่เปลี่ยน แต่รายการนี้มีอยู่
 * เพื่อให้ BDI แก้ได้เป็นเรื่องปกติ ถ้า cache ไว้หนึ่งวัน แอดมินที่เพิ่งแก้ป้ายแล้วกด
 * refresh จะไม่เห็นอะไรเปลี่ยนไปอีกยี่สิบสี่ชั่วโมง แล้วรายงานว่า admin API พัง
 * (เจอจริงตอนทดสอบ: เพิ่มรหัสใหม่แล้วเซิร์ฟเวอร์มีแล้ว แต่หน้าเว็บยังเป็นชุดเดิม)
 *
 * ราคาที่จ่ายคือ conditional request หนึ่งครั้งต่อการเปิดหน้า — express ใส่ ETag ให้เอง
 * payload ไม่ถึงสามกิโลไบต์ และรอบที่ไม่เปลี่ยนจบที่ 304 ไม่มีเนื้อความส่งกลับ
 */
datasetChoiceRouter.use((_req, res, next) => {
  res.set("Cache-Control", "no-cache");
  next();
});

datasetChoiceRouter.get("/", (_req, res) => {
  res.json({ choices: activeChoiceMap() });
});
