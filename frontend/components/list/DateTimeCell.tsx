import { thaiDateParts } from "@/lib/status";

/**
 * ช่องวันที่ในตารางคำขอ — วันที่บรรทัดบน เวลาบรรทัดล่าง
 *
 * BDI ขอเวลาเพิ่มเมื่อ 2026-09-13: สองคำขอที่ขยับวันเดียวกันเคยอ่านเป็น "เท่ากัน" ทั้งที่
 * การเรียงวางมันคนละที่ ซึ่งอ่านแล้วเหมือนการเรียงมั่ว ทั้งที่ข้อมูลถูก — เวลาคือสิ่งที่
 * ทำให้ลำดับที่เห็นอธิบายตัวเองได้
 *
 * **แยกบรรทัด ไม่ใช่ต่อท้ายบรรทัดเดียว** เพราะคอลัมน์กว้าง 8rem ตายตัว (หัวตารางกับแถว
 * เป็นคนละ grid จึงใช้ auto ไม่ได้) "13 ก.ย. 2569 17:45" ในความกว้างนั้นจะขึ้นบรรทัดใหม่เอง
 * อยู่ดี แต่ตัดตรงไหนก็ได้แล้วแต่ที่ว่าง — กำหนดเองจึงได้ขอบขวาที่ตรงกันทุกแถว
 *
 * เป็น component ไม่ใช่โค้ดซ้ำสี่ที่ (สองตาราง × สองคอลัมน์) เพราะกติกา "จอแคบต้องมีคำ
 * นำหน้า" ด้านล่างต้องเหมือนกันทั้งสี่ที่ ไม่งั้นวันหลังแก้ที่เดียวลืมอีกสามที่
 */
export function DateTimeCell({ value, label }: { value: string | null; label: string }) {
  const parts = thaiDateParts(value);

  return (
    <span className="text-[13px] text-ink-muted md:text-right">
      {/* ต่ำกว่า md หัวตารางซ่อนตัวเอง แถวจึงเหลือวันที่สองก้อนที่ไม่มีชื่อกำกับ */}
      <span className="md:hidden">{label}: </span>
      {parts ? (
        <>
          <span className="md:block">{parts.date}</span>{" "}
          <span className="md:block text-[12px] text-ink-subtle">{parts.time} น.</span>
        </>
      ) : (
        "—"
      )}
    </span>
  );
}
