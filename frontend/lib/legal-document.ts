import type { LegalDocument, SkippedLegalDocument } from "@/lib/types";

/**
 * ชื่อที่หน้าจอเรียกเอกสารฉบับหนึ่ง
 *
 * รหัส `A0`–`A4` เคยเป็นสิ่งที่ผู้ใช้เห็น — บนแท็บเลือกเอกสาร บนหัวกล่องลงนาม และในชื่อไฟล์
 * ที่ดาวน์โหลดออกไป BDI ขอให้เอาออกทั้งหมดเมื่อ 2026-09-04 เพราะมันเป็นรหัสภายในที่ไม่มี
 * ความหมายกับหน่วยงานที่กำลังอ่านสัญญาอยู่ — เขาเรียกเอกสารพวกนี้ว่า "ผนวก 1" ตามที่
 * ฝ่ายกฎหมายเขียนไว้บนหัวกระดาษ
 *
 * `shortname` เป็น null ได้ (A4 ไม่มี) จึงตกกลับไปใช้ชื่อเต็ม ไม่ใช่ตกกลับไปใช้รหัส —
 * ทั้งข้อนี้คือสิ่งที่ขอให้เลิกแสดง
 */
export function documentLabel(doc: LegalDocument | SkippedLegalDocument): string {
  return doc.shortname ?? doc.name;
}

/**
 * คำเตือนประจำเอกสารฉบับหนึ่ง — มีค่าแล้วคืนค่า ว่างหรือมีแต่ช่องว่างถือว่าไม่มี
 *
 * **ที่แสดงมีที่เดียว: กล่องอ่าน/ลงนามของผู้มีอำนาจ (`SigningDialog`, `perDocument = true`)**
 * ซึ่งเป็นขั้นที่เปิดเอกสารทีละฉบับแล้วกดเห็นชอบ และเป็นขั้นเดียวที่มีปุ่ม "ไม่เกี่ยวข้อง"
 *
 * เคยตัดสินกลับกันเมื่อ 2026-09-06 ว่าคำเตือนเป็นคุณสมบัติของ*ตัวเอกสาร* จึงต้องขึ้นทุกที่ที่
 * เอกสารถูกยื่นให้อ่าน รวมถึงการ์ด "เอกสารข้อตกลง" **BDI กลับคำเมื่อ 2026-09-07** เพราะ
 * คำเตือนที่มีอยู่จริงฉบับเดียว (ผนวก 3) ไม่ได้บอกข้อเท็จจริงเฉย ๆ แต่**สั่งให้กดปุ่ม** —
 * และปุ่มนั้นไม่มีอยู่บนหน้าที่แค่เปิดอ่าน คนกรอกฟอร์มที่เห็นมันตอนตรวจเอกสารก่อนนำส่งจึง
 * ได้คำสั่งที่ทำตามไม่ได้ ไม่ใช่ข้อมูลเพิ่ม
 *
 * กฎที่ใช้แทน: **คำเตือนอยู่ในขั้นที่ทำตามคำเตือนนั้นได้** ไม่ใช่ทุกที่ที่เอกสารถูกเปิดอ่าน
 * ถ้าวันหนึ่งมีคำเตือนที่ไม่ได้สั่งให้กดอะไร ให้ทบทวนกฎนี้ใหม่ อย่าเพิ่งแอบเติมที่แสดง
 */
export function legalNoticeOf(doc: LegalDocument): string | null {
  const notice = doc.legalNotice?.trim();
  return notice ? notice : null;
}
