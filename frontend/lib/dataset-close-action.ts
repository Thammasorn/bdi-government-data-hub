import type { RequestStatus } from "./status";

/**
 * ปุ่มเดียวของผู้ประสานงานของหน่วยงานที่ "เอาคำขอชุดข้อมูลใบนี้ออกจากงานที่ค้างอยู่"
 * — ให้ผลอย่างเดียวคือ **ยกเลิก** ไม่ว่าคำขอจะเคยนำส่งไปแล้วหรือยัง
 *
 * เคยมีสองทาง: ร่างที่ไม่เคยนำส่งถูกลบทิ้งจริง ส่วนใบที่เคยนำส่งถูกยกเลิก (2026-09-23)
 * การ์ด 2026-09-25 สั่งให้เหลือทางเดียว — `DELETE /api/dataset-requests/:id` ยกเลิกเสมอ
 * และแถวไม่หายออกจากระบบอีกแล้ว คำบนปุ่มจึงพูดว่า "ยกเลิก" เสมอเช่นกัน
 *
 * ที่ยังต้องมีไฟล์นี้อยู่ ทั้งที่เหลือค่าเดียว: ปุ่มในตาราง · ปุ่มบนหน้ารายละเอียด ·
 * กล่องยืนยัน · toast ทั้งสองหน้า อ่านคำจากที่เดียวกัน ถ้าวันหนึ่งข้อความเปลี่ยน
 * จะได้ไม่เหลือหน้าที่พูดคนละอย่างกับสิ่งที่ server ทำ
 */
export interface DatasetCloseAction {
  /** คำบนปุ่มในตาราง — สั้นเพราะอยู่ในวงกลมมุมแถว */
  short: string;
  /** คำกริยาที่เอาไปต่อกับชื่อคำขอได้ ใช้ทั้งใน aria-label และในประโยคของกล่องยืนยัน */
  verb: string;
  modalTitle: string;
  modalDescription: string;
  /** บรรทัดที่บอกผลที่ตามมา */
  note: string;
  confirmLabel: string;
  doneTitle: string;
  doneDetail: (requestNumber: string) => string;
  failTitle: string;
}

/**
 * สถานะที่ปุ่มนี้ขึ้น — คำขอที่อยู่ในมือของหน่วยงานเท่านั้น
 *
 * `SUBMITTED` / `UNDER_REVIEW` คือใบที่ค้างอยู่ที่ด่านของ BDI มีคนกำลังอ่านอยู่ และ
 * ฝั่ง server ปฏิเสธทั้งสองสถานะนี้ (ตัดสิน 2026-09-23 ยืนยันอีกครั้ง 2026-09-25)
 * ปุ่มที่กดแล้วได้ 409 แย่กว่าไม่มีปุ่ม — กติกาเดียวกับที่ `canDelete` ใช้ซ่อนปุ่มจาก
 * เจ้าหน้าที่ BDI อยู่แล้ว
 */
export const CLOSEABLE_STATUSES: RequestStatus[] = ["DRAFT", "RETURNED"];

